#!/bin/sh
# Compiles TestMapListener.java for Java 8 against the JUnit Platform 1.8 API
# and writes its bytes into src/testmap-listener.ts, which embeds them in the
# binary. Run it after editing the listener:
#   sh packs/jvm/src/assets/testmap/build.sh <junit-platform-launcher.jar> <junit-platform-engine.jar> <junit-platform-commons.jar>
set -eu
here=$(cd "$(dirname "$0")" && pwd)
out=$(mktemp -d)
javac --release 8 -nowarn -cp "$1:$2:$3" -d "$out" "$here/gauntlet/TestMapListener.java"
bytes=$(base64 < "$out/gauntlet/TestMapListener.class" | tr -d '\n')
cat > "$here/../../testmap-listener.ts" <<TS
// Generated by src/assets/testmap/build.sh from src/assets/testmap/gauntlet/TestMapListener.java: don't edit.

/** The compiled JUnit Platform listener that writes what each test class executes (spec 0013). */
export const LISTENER_CLASS = "gauntlet.TestMapListener"

/** Its class file (Java 8), base64. */
export const LISTENER_BYTES = "$bytes"
TS
rm -rf "$out"
